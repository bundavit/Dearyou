    }

    public function test_test_email_rejects_missing_recipient_key_and_fake_transport(): void
    {
        Notification::fake();
        $this->actingAs(User::factory()->create(['role' => User::ROLE_ADMIN]));
        app(PlatformSettings::class)->update(['feedback_notify_email' => '']);
        $this->post('/admin/email-tools/feedback-test')->assertSessionHasErrors('email_tools');
        app(PlatformSettings::class)->update(['feedback_notify_email' => 'qa@example.test']);
        config(['mail.default' => 'resend', 'services.resend.key' => '']);
        $this->post('/admin/email-tools/feedback-test')->assertSessionHasErrors('email_tools');
        config(['mail.default' => 'array']);
        $this->post('/admin/email-tools/feedback-test')->assertSessionHasErrors('email_tools');
        Notification::assertNothingSent();
    }

    public function test_admin_test_reports_enqueue_failure(): void
    {
        config(['queue.default' => 'database', 'queue.connections.database.table' => 'missing_jobs', 'mail.default' => 'log']);
        app(PlatformSettings::class)->update(['feedback_notify_email' => 'qa@example.test']);
        $this->actingAs(User::factory()->create(['role' => User::ROLE_ADMIN]))
            ->post('/admin/email-tools/feedback-test')->assertSessionHasErrors('email_tools')->assertSessionMissing('success');
    }

    public function test_queue_diagnostics_use_configured_table_and_queue(): void
    {
        Schema::create('diagnostic_jobs', function ($table) {
            $table->id();
            $table->string('queue');
            $table->integer('created_at');
            $table->integer('available_at');
            $table->integer('reserved_at')->nullable();
        });
        config(['queue.default' => 'database', 'queue.connections.database.table' => 'diagnostic_jobs', 'queue.connections.database.queue' => 'mail']);
        foreach ([['mail', null, -600], ['mail', null, 600], ['mail', now()->timestamp, -60], ['other', null, -900]] as [$queue, $reserved, $delay]) {
            DB::table('diagnostic_jobs')->insert(['queue' => $queue, 'reserved_at' => $reserved, 'created_at' => now()->subMinutes(10)->timestamp, 'available_at' => now()->timestamp + $delay]);
        }
        $result = app(EmailQueueDiagnostics::class)->pending();
        $this->assertTrue($result['available']);
        $this->assertSame(2, $result['waiting']);
        $this->assertSame(1, $result['reserved']);
        $this->assertSame(1, $result['delayed']);
        $this->assertNotNull($result['oldest']);
    }

    public function test_retry_only_accepts_listed_email_jobs(): void
    {
        config(['queue.default' => 'database']);
        $emailId = (string) Str::uuid();
        $otherId = (string) Str::uuid();
        foreach ([$emailId => VerifyEmail::class, $otherId => 'App\\Jobs\\RebuildSearch'] as $id => $class) {
            DB::table('failed_jobs')->insert(['uuid' => $id, 'connection' => 'database', 'queue' => 'default',
                'payload' => json_encode(['displayName' => $class]), 'exception' => 'private-exception-data', 'failed_at' => now()]);
        }
        $this->actingAs(User::factory()->create(['role' => User::ROLE_ADMIN]));
        Artisan::shouldReceive('call')->once()->with('queue:retry', ['id' => [$emailId]])->andReturn(0);
        $this->post('/admin/email-tools/failed-jobs/retry', ['jobs' => [$otherId]])->assertSessionHasErrors('email_tools');
        $this->post('/admin/email-tools/failed-jobs/retry', ['jobs' => [$emailId]])->assertSessionHas('success');
        $this->get('/admin/email-tools')->assertOk()->assertDontSee('private-exception-data')->assertDontSee('Recent verification codes');
    }
}
