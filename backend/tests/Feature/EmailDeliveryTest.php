class EmailDeliveryTest extends TestCase
{
    use RefreshDatabase;

    private ?string $mailLog = null;

    protected function tearDown(): void
    {
        if ($this->mailLog !== null && is_file($this->mailLog)) {
            unlink($this->mailLog);
        }
        parent::tearDown();
    }

    private function logQueue(): void
    {
        $this->mailLog = tempnam(sys_get_temp_dir(), 'dearyou-mail-test-');
        config([
            'queue.default' => 'database',
            'mail.default' => 'log',
            'mail.mailers.log.channel' => 'delivery_test',
            'logging.channels.delivery_test' => ['driver' => 'single', 'path' => $this->mailLog, 'level' => 'debug'],
            'mail.from.address' => 'qa@dearyou.test',
        ]);
    }

    private function runOneJob(): void
    {
        app('queue.worker')->runNextJob('database', 'default', new WorkerOptions(sleep: 0, maxTries: 1));
    }

    private function queuedCode(): string
    {
        // This payload was generated by this test in its isolated in-memory database.
        $payload = json_decode(DB::table('jobs')->latest('id')->value('payload'), true);

        return unserialize($payload['data']['command'])->notification->code;
    }

    public function test_registration_runs_through_database_queue_and_logged_code_verifies_account(): void
    {
        $this->logQueue();
        $this->post('/register', ['name' => 'QA Writer', 'email' => 'qa@example.test',
            'password' => 'QaPassword123!', 'password_confirmation' => 'QaPassword123!'])->assertRedirect('/verify-email');
        $this->assertDatabaseCount('jobs', 1);
        $code = $this->queuedCode();
        $user = User::where('email', 'qa@example.test')->firstOrFail();
        $this->assertFalse($user->hasVerifiedEmail());
        $this->assertTrue(Hash::check($code, DB::table('email_verification_codes')->value('code')));
        $this->runOneJob();
        $this->assertDatabaseCount('jobs', 0);
        $this->assertDatabaseCount('failed_jobs', 0);
        $this->assertStringContainsString('Your DearYou verification code', file_get_contents($this->mailLog));
        $this->assertStringContainsString($code, file_get_contents($this->mailLog));
        $this->post('/verify-email', ['code' => $code])->assertRedirect('/letters');
        $this->assertTrue($user->fresh()->hasVerifiedEmail());
        $this->assertDatabaseCount('email_verification_codes', 0);
    }

    public function test_worker_skips_superseded_code_and_delivers_latest_resend(): void
    {
        $this->logQueue();
        $user = User::factory()->unverified()->create();
        $user->sendEmailVerificationNotification();
        $oldCode = $this->queuedCode();
        $this->actingAs($user)->post('/email/verification-notification')->assertSessionHas('status', 'verification-code-sent');
        $newCode = $this->queuedCode();
        // Use a definitely stale code even in the one-in-a-million random collision case.
        if ($oldCode === $newCode) {
            $this->actingAs($user)->post('/email/verification-notification')->assertRedirect();
            $newCode = $this->queuedCode();
        }
        $this->assertNotSame($oldCode, $newCode);
        $this->runOneJob();
        $this->assertSame('', file_get_contents($this->mailLog));
        while (DB::table('jobs')->exists()) {
            $this->runOneJob();
        }
        $mail = file_get_contents($this->mailLog);
        $this->assertStringContainsString($newCode, $mail);
        $this->assertStringNotContainsString($oldCode, $mail);
        $this->post('/verify-email', ['code' => $oldCode])->assertSessionHasErrors('code');
        $this->post('/verify-email', ['code' => $newCode])->assertRedirect('/letters');
    }

    public function test_expired_queued_code_is_not_delivered_or_accepted(): void
    {
        $this->logQueue();
        $user = User::factory()->unverified()->create();
        $user->sendEmailVerificationNotification();
        $code = $this->queuedCode();
        $this->travel(11)->minutes();
        $this->runOneJob();
        $this->assertSame('', file_get_contents($this->mailLog));
        $this->assertDatabaseCount('jobs', 0);
        $this->actingAs($user)->post('/verify-email', ['code' => $code])->assertSessionHasErrors('code');
        $this->assertFalse($user->fresh()->hasVerifiedEmail());
    }

    public function test_failed_resend_preserves_previous_code_and_shows_recoverable_error(): void
    {
        config(['queue.default' => 'database', 'queue.connections.database.table' => 'missing_jobs']);
        $user = User::factory()->unverified()->create();
        DB::table('email_verification_codes')->insert(['user_id' => $user->id, 'code' => Hash::make('123456'),
            'attempts' => 0, 'expires_at' => now()->addMinutes(10), 'created_at' => now(), 'updated_at' => now()]);
        $this->actingAs($user)->from('/verify-email')->post('/email/verification-notification')
            ->assertRedirect('/verify-email')->assertSessionHasErrors('delivery');
        $this->withCookie(config('session.cookie'), session()->getId());
        $this->get('/verify-email')->assertSee('We could not request a verification email.');
        $this->post('/verify-email', ['code' => '123456'])->assertRedirect('/letters');
        $this->assertTrue($user->fresh()->hasVerifiedEmail());
    }

    public function test_registration_survives_enqueue_failure_without_claiming_email_was_sent(): void
    {
        config(['queue.default' => 'database', 'queue.connections.database.table' => 'missing_jobs']);
        $this->post('/register', ['name' => 'QA Writer', 'email' => 'qa@example.test',
            'password' => 'QaPassword123!', 'password_confirmation' => 'QaPassword123!'])
            ->assertRedirect('/verify-email')->assertSessionHasErrors('delivery');
        $this->assertAuthenticated();
        $this->assertDatabaseCount('users', 1);
        $this->assertDatabaseCount('email_verification_codes', 0);
        $this->withCookie(config('session.cookie'), session()->getId());
        $this->get('/verify-email')->assertOk()->assertSee('Your account was created, but we could not request the verification email.');
    }

    public function test_feedback_and_admin_test_use_the_application_queue_and_mail_log(): void
    {
        $this->logQueue();
        app(PlatformSettings::class)->update(['feedback_notify_email' => 'feedback@example.test']);
        $this->post('/feedback', ['category' => 'bug', 'message' => 'Synthetic queued feedback check.'])->assertRedirect('/#feedback');
        $this->assertDatabaseCount('jobs', 1);
        $this->runOneJob();
        $this->assertStringContainsString('New DearYou feedback', file_get_contents($this->mailLog));
        $admin = User::factory()->create(['role' => User::ROLE_ADMIN]);
        $count = Feedback::count();
        $this->actingAs($admin)->post('/admin/email-tools/feedback-test')->assertRedirect()->assertSessionHas('success');
        $this->assertSame($count, Feedback::count());
        $this->assertDatabaseCount('jobs', 1);
        $this->runOneJob();
        $this->assertDatabaseCount('failed_jobs', 0);
        $this->assertStringContainsString('DearYou feedback delivery test', file_get_contents($this->mailLog));
        $this->assertStringContainsString('QA-FEEDBACK-', file_get_contents($this->mailLog));
    }

    public function test_admin_test_uses_saved_recipient_and_is_throttled(): void
    {
        Notification::fake();
        config(['mail.default' => 'resend', 'services.resend.key' => 'fake-key', 'dearyou.feedback_notify_email' => 'fallback@example.test']);
        app(PlatformSettings::class)->update(['feedback_notify_email' => 'saved@example.test']);
        $this->actingAs(User::factory()->create(['role' => User::ROLE_ADMIN]));
        foreach (range(1, 3) as $attempt) {
            $this->post('/admin/email-tools/feedback-test')->assertRedirect();
        }
        $this->post('/admin/email-tools/feedback-test')->assertStatus(429);
        Notification::assertSentOnDemand(FeedbackDeliveryTest::class, fn ($notification, $channels, $notifiable) => $notifiable->routes['mail'] === 'saved@example.test');
        $this->assertDatabaseCount('feedback', 0);
    }

    public function test_creator_cannot_send_admin_test_or_retry_jobs(): void
    {
        Notification::fake();
